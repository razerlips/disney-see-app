// 画面に出すときだけ、施設名を短く・分かりやすくする。
// お気に入り・カスタム順・運営予定時間などはデータ上の名前（正式名）で照合しているので、名前そのものは変えない。

// 「ディズニーシー・トランジットスチーマーライン（…）」「ディズニーシー・エレクトリックレールウェイ（…）」の
// 頭の「ディズニーシー・」は、シー専用のアプリでは分かりづらいので取る
export const displayName = (name) => String(name ?? "").replace(/^ディズニーシー・(?=トランジットスチーマーライン|エレクトリックレールウェイ)/, "");
